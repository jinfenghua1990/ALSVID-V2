const { test } = require('node:test');
const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const { randomUUID } = require('node:crypto');
const path = require('node:path');
const { Client } = require('pg');
const Fastify = require('fastify');
const { createAuth } = require('../auth');
const { apiAccessHook } = require('../access-policy');
const { runAsActor } = require('../audit-context');
const { createPortalStore, registerPortalRoutes } = require('../portal');

test('reviewed portals isolate users, ownership and service records through revocation', async t => {
  const url = process.env.TEST_DATABASE_URL;
  assert.ok(url, 'Use an isolated local TEST_DATABASE_URL');
  const parsed = new URL(url);
  assert.ok(['127.0.0.1', 'localhost'].includes(parsed.hostname) && /^\/alsvid_v2_test_/.test(parsed.pathname), 'Refuse non-test databases');
  const c = new Client({ connectionString: url }); await c.connect();
  await c.query(readFileSync(path.join(__dirname, '../schema.sql'), 'utf8'));
  const auth = createAuth(url), portal = createPortalStore(url), app = Fastify();
  t.after(async () => { await app.close(); await auth.close(); await portal.close(); await c.end(); });
  app.addHook('onRequest', apiAccessHook(auth, req => req.headers['test-session']));
  app.addHook('onRequest', (req, reply, done) => runAsActor(req.user?.username || 'anonymous', done));
  registerPortalRoutes(app, { auth, portal });
  app.get('/api/finance/private', async () => ({ secret: 'private' }));
  const password = 'Test-password-123';
  await auth.setup('portal-test-admin', password);
  const admin = (await auth.login('portal-test-admin', password)).token;
  await auth.createUser({ username: 'portal-test-viewer', role: 'viewer', password }, 'portal-test-admin');
  const viewer = (await auth.login('portal-test-viewer', password)).token;
  const request = (method, url, body, token) => app.inject({ method, url, payload: body, headers: token ? { 'test-session': token } : {} });
  const create = (username, role, reviewNote = 'Identity verified for isolated test') => request('POST', '/api/portal-management/accounts', { username, role, password, reviewNote }, admin);
  for (const url of ['/api/portal/vehicles', '/api/portal/vehicle-requests', '/api/portal/service-requests', '/api/portal-management/accounts', '/api/portal-management/vehicle-requests', '/api/portal-management/service-requests']) {
    assert.equal((await request('GET', url)).statusCode, 401);
    assert.equal((await request('GET', url, null, viewer)).statusCode, 403);
  }
  assert.equal((await create('bad-portal', 'admin')).statusCode, 400);
  assert.equal((await create('bad-portal', 'owner', '')).statusCode, 400);
  const users = {};
  for (const [name, role] of [['owner1', 'owner'], ['owner2', 'owner'], ['dealer1', 'dealer'], ['dealer2', 'dealer']]) {
    const res = await create(name, role); assert.equal(res.statusCode, 201, res.body);
    users[name] = { ...res.json(), token: (await auth.login(name, password)).token };
    assert.equal((await request('GET', '/api/finance/private', null, users[name].token)).statusCode, 403);
    assert.equal((await request('GET', '/api/portal-management/accounts', null, users[name].token)).statusCode, 403);
    assert.equal((await request('POST', '/api/portal-management/accounts', {}, users[name].token)).statusCode, 403);
  }
  assert.equal((await request('GET', '/api/portal/vehicles', null, admin)).statusCode, 403);
  assert.deepEqual((await auth.listUsers()).map(u => u.role).sort(), ['admin', 'viewer']);
  await assert.rejects(auth.createUser({ username: 'bypass-portal', role: 'owner', password }, 'portal-test-admin'), /角色无效/);
  await assert.rejects(auth.updateUser(users.owner1.id, { role: 'admin' }, 'portal-test-admin'), /门户账号不能变更角色/);
  await c.query("INSERT INTO vins(id,vin,model,factory,batch) VALUES('portal-vin-1','LTEST123456789001','Owner model','Private factory','Private batch'),('portal-vin-2','LTEST123456789002','Other model','Private factory','Private batch')");
  const claim = async (name, vin = 'LTEST123456789001') => {
    const res = await request('POST', '/api/portal/vehicle-requests', { vin, note: 'Please verify purchase evidence', user_id: users.owner2.id }, users[name].token);
    assert.equal(res.statusCode, 201, res.body); return res.json();
  };
  const review = (id, decision, token = admin) => request('POST', `/api/portal-management/vehicle-requests/${id}/review`, { decision, note: 'Evidence checked by administrator' }, token);
  const a = await claim('owner1');
  assert.equal((await request('POST', '/api/portal/vehicle-requests', { vin: a.vin, note: 'Duplicate' }, users.owner1.token)).statusCode, 409);
  assert.deepEqual((await request('GET', '/api/portal/vehicles', null, users.owner1.token)).json(), []);
  assert.deepEqual((await request('GET', '/api/portal/vehicle-requests', null, users.owner2.token)).json(), []);
  assert.equal((await review(a.id, 'approve', users.owner1.token)).statusCode, 403);
  assert.equal((await review(a.id, 'approve')).statusCode, 200);
  const ownerVehicles = (await request('GET', '/api/portal/vehicles', null, users.owner1.token)).json();
  assert.deepEqual(ownerVehicles.map(v => v.id), ['portal-vin-1']);
  assert.deepEqual(Object.keys(ownerVehicles[0]).sort(), ['id', 'vin', 'model', 'producedAt'].sort());
  assert.equal(JSON.stringify(ownerVehicles).includes('Private'), false);
  const b = await claim('owner2'); assert.equal((await review(b.id, 'approve')).statusCode, 409);
  const missing = await claim('owner2', 'LTEST123456789999');
  assert.equal((await review(missing.id, 'approve')).statusCode, 400);
  assert.equal((await review(missing.id, 'reject')).statusCode, 200);
  const d = await claim('dealer1'); assert.equal((await review(d.id, 'approve')).statusCode, 200);
  assert.deepEqual((await request('GET', '/api/portal/vehicles', null, users.dealer2.token)).json(), []);
  const claims = await Promise.all([claim('owner1', 'LTEST123456789002'), claim('owner2', 'LTEST123456789002')]);
  const approvals = await Promise.all(claims.map(row => review(row.id, 'approve')));
  assert.deepEqual(approvals.map(r => r.statusCode).sort(), [200, 409]);

  const service = { id: randomUUID(), vinId: 'portal-vin-1', description: 'Check brakes' };
  assert.equal((await request('POST', '/api/portal/service-requests', service, users.owner2.token)).statusCode, 403);
  assert.equal((await request('POST', '/api/portal/service-requests', { ...service, vinId: 'unknown' }, users.owner1.token)).statusCode, 403);
  const retries = await Promise.all([request('POST', '/api/portal/service-requests', service, users.owner1.token), request('POST', '/api/portal/service-requests', service, users.owner1.token)]);
  assert.deepEqual(retries.map(r => r.statusCode), [201, 201]);
  assert.equal((await c.query('SELECT count(*)::int AS n FROM portal_service_requests WHERE id=$1', [service.id])).rows[0].n, 1);
  assert.equal((await request('POST', '/api/portal/service-requests', { ...service, description: 'Changed' }, users.owner1.token)).statusCode, 409);
  assert.deepEqual((await request('GET', '/api/portal/service-requests', null, users.dealer1.token)).json(), []);
  const serviceUrl = `/api/portal-management/service-requests/${service.id}/review`;
  assert.equal((await request('POST', serviceUrl, { decision: 'accept', note: 'Accepted' }, users.owner1.token)).statusCode, 403);
  const acceptance = await Promise.all([request('POST', serviceUrl, { decision: 'accept', note: 'Accepted' }, admin), request('POST', serviceUrl, { decision: 'accept', note: 'Accepted' }, admin)]);
  assert.deepEqual(acceptance.map(r => r.statusCode).sort(), [200, 409]);
  const repairs = (await c.query("SELECT id FROM repairs WHERE fault='Check brakes'")).rows; assert.equal(repairs.length, 1);
  await c.query("UPDATE repairs SET status='维修中',old_part='private recovery notes' WHERE id=$1", [repairs[0].id]);
  const progress = (await request('GET', '/api/portal/service-requests', null, users.owner1.token)).json();
  assert.equal(progress[0].repairStatus, '维修中'); assert.ok(progress[0].workOrderNo);
  assert.equal(JSON.stringify(progress).includes('private recovery'), false);
  assert.equal((await review(a.id, 'revoke')).statusCode, 200);
  assert.equal((await request('GET', '/api/portal/vehicles', null, users.owner1.token)).json().some(v => v.id === 'portal-vin-1'), false);
  assert.deepEqual((await request('GET', '/api/portal/service-requests', null, users.owner1.token)).json(), []);
  assert.equal((await request('POST', '/api/portal/service-requests', { ...service, id: randomUUID() }, users.owner1.token)).statusCode, 403);
  assert.equal((await review(b.id, 'approve')).statusCode, 200);
  assert.deepEqual((await request('GET', '/api/portal/service-requests', null, users.owner2.token)).json(), []);
  assert.equal((await request('PATCH', `/api/portal-management/accounts/${users.dealer1.id}`, { enabled: false }, admin)).statusCode, 200);
  assert.equal((await request('GET', '/api/portal/vehicles', null, users.dealer1.token)).statusCode, 401);
  assert.equal(await auth.login('dealer1', password), null);
  assert.equal((await request('POST', '/api/portal/password', { oldPassword: 'wrong', newPassword: 'New-test-password' }, users.owner2.token)).statusCode, 400);
  assert.equal((await request('POST', '/api/portal/password', { oldPassword: password, newPassword: 'New-test-password' }, users.owner2.token)).statusCode, 200);
  assert.equal((await request('GET', '/api/portal/vehicles', null, users.owner2.token)).statusCode, 401);
  assert.equal(await auth.login('owner2', password), null);
  assert.ok(await auth.login('owner2', 'New-test-password'));
  assert.equal((await request('POST', `/api/portal-management/accounts/${users.dealer2.id}/password`, { newPassword: 'Reset-test-password' }, admin)).statusCode, 200);
  assert.equal((await request('GET', '/api/portal/vehicles', null, users.dealer2.token)).statusCode, 401);
  const audit = (await c.query("SELECT actor FROM audit_log WHERE action LIKE 'portal.vehicle.%' OR action LIKE 'portal.service.%'")).rows;
  assert.ok(audit.length >= 12); assert.ok(audit.every(row => row.actor !== 'anonymous' && row.actor !== 'system'));
});
